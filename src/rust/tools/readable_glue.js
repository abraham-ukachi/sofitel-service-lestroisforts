'use strict';

const fs = require('fs');
const acorn = require('acorn');
const eslintScope = require('eslint-scope');

// 📖 the readable names for wasm-bindgen's one-letter variables
const READABLE_NAMES = { i: 'index', f: 'closure', e: 'error', x: 'value', a: 'closureState' };

// 🗂️ the glue file to fix
const gluePath = process.argv[2];
let source = fs.readFileSync(gluePath, 'utf8');

/**
 * `readableNameFor` - Function 🏷️
 *
 * Picks a readable, collision-free name for a one-letter variable in its scope.
 *
 * @param { string } shortName - the one-letter name
 * @param { object } scope - its eslint-scope scope
 * @returns { string } the readable name
 */
function readableNameFor(shortName, scope) {
  const baseName = READABLE_NAMES[shortName] || 'value' + shortName.toUpperCase();
  const takenNames = new Set();
  for (let current = scope; current; current = current.upper) current.variables.forEach((variable) => takenNames.add(variable.name));
  scope.through.forEach((reference) => takenNames.add(reference.identifier.name));
  let candidate = baseName;
  for (let suffix = 2; takenNames.has(candidate); suffix++) candidate = baseName + suffix;
  return candidate;
}

// 🔁 rename one variable per pass (so every offset stays valid), until none is left
for (let pass = 0; pass < 200; pass++) {
  const tree = acorn.parse(source, { ecmaVersion: 'latest', sourceType: 'script', ranges: true });
  const scopeManager = eslintScope.analyze(tree, { ecmaVersion: 2022, sourceType: 'script' });
  let target = null;
  for (const scope of scopeManager.scopes) {
    target = scope.variables.find((variable) => variable.name.length === 1 && variable.defs.length);
    if (target) {
      target.scopeRef = scope;
      break;
    }
  }
  if (!target) break;
  const newName = readableNameFor(target.name, target.scopeRef);
  const positions = new Set();
  target.identifiers.forEach((identifier) => positions.add(identifier.start));
  target.references.forEach((reference) => positions.add(reference.identifier.start));
  [...positions]
    .sort((first, second) => second - first)
    .forEach((start) => {
      source = source.slice(0, start) + newName + source.slice(start + target.name.length);
    });
}

// 🏷️ stamp the marker on top (once)
const MARKER = '// 🦀 LTF readable glue: generated by wasm-bindgen, one-letter names renamed by tools/readable_glue.js\n';
if (!source.includes('LTF readable glue')) source = MARKER + source;

fs.writeFileSync(gluePath, source);
console.log('readable glue ✅', gluePath);
